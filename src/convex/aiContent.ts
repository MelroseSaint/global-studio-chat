import { v } from "convex/values";

import { action } from "./_generated/server";

/**
 * PureWire's anti-AI-content layer.
 *
 * The platform is built on original, human-made work — "say it anyway"
 * means *your* voice, not a machine's. This module scans posts, comments,
 * and stories before they go live:
 *
 * - Text that clearly identifies itself as AI-generated is blocked at
 *   creation with an honest message.
 * - Text that *reads* machine-made (heavy formulaic phrasing, including
 *   bare "as an AI" claims) is flagged for admin review instead of
 *   blocked, so genuine human writing is never rejected on a hunch.
 * - Images with generator metadata baked into the file (Stable Diffusion,
 *   Midjourney, DALL·E, NovelAI, ComfyUI, etc.) are blocked.
 *
 * Reading file bytes is only available inside Convex actions, so the
 * media scan is an action that mutations call via `ctx.runAction`.
 */

export type AiScanResult =
  | { status: "clean" }
  | { status: "review"; reason: string }
  | { status: "blocked"; reason: string };

/**
 * Messages that are overwhelmingly likely to be AI-generated. Each pattern
 * requires the full self-identifying phrase so legitimate human speech
 * like "as an AI researcher" or "I'm an AI engineer" is never blocked.
 */
const HARD_BLOCK_TEXT: RegExp[] = [
  /\bas an ai (?:language model|assistant|chatbot)\b/i,
  /\bi['’]?m an ai (?:language model|assistant|chatbot)\b/i,
  /\bi am an ai (?:language model|assistant|chatbot)\b/i,
  /\bthis (?:post|content|text|paragraph) (?:was|is) (?:written|generated|created|produced) by (?:an )?ai\b/i,
  /\bgenerated by (?:an )?(?:ai|chatgpt|gpt|dall[·e ]|midjourney)\b/i,
  /\bchatgpt (?:wrote|made|generated)\b/i,
];

/**
 * Formulaic phrasing that LLMs overuse — including bare "as an AI" and
 * "I'm an AI" claims, which are demoted here so that a human decides
 * instead of a false-positive block. A post that stacks several of these
 * reads machine-made and is flagged for admin review.
 */
const FORMULAIC_PHRASES = [
  "as an ai",
  "i'm an ai",
  "i am an ai",
  "as a language model",
  "moreover",
  "furthermore",
  "additionally",
  "in conclusion",
  "to summarize",
  "it is important to note",
  "it's important to",
  "it is worth noting",
  "delve",
  "underscore",
  "landscape",
  "in today's",
  "in the ever-evolving",
  "a testament to",
  "at the end of the day",
  "game-changer",
  "seamlessly",
  "cutting-edge",
  "let's dive",
  "it cannot be overstated",
  "it goes without saying",
  "notably,",
  "crucially,",
  "significantly,",
  "all in all",
  "overall,",
];

const MIN_SUSPICIOUS_LENGTH = 120;
const FORMULAIC_HITS_FOR_REVIEW = 5;

/** Scan post/comment/story text for signs of AI generation. */
export function scanText(content: string): AiScanResult {
  const text = content.trim();
  if (text.length === 0) {
    return { status: "clean" };
  }
  for (const pattern of HARD_BLOCK_TEXT) {
    if (pattern.test(text)) {
      return {
        status: "blocked",
        reason: "This reads like AI-generated text, which isn't allowed on PureWire.",
      };
    }
  }
  if (text.length >= MIN_SUSPICIOUS_LENGTH) {
    const lower = text.toLowerCase();
    let hits = 0;
    for (const phrase of FORMULAIC_PHRASES) {
      if (lower.includes(phrase)) {
        hits++;
      }
    }
    if (hits >= FORMULAIC_HITS_FOR_REVIEW) {
      return {
        status: "review",
        reason: "Heavy formulaic phrasing — flagged for a human check.",
      };
    }
  }
  return { status: "clean" };
}

