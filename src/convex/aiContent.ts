/**
 * Shared validator for the media-scan verdict passed from the client into
 * the post/story mutations. Lives here so both callers stay in sync.
 */
export const AI_MEDIA_STATUS = v.union(
  v.literal("clean"),
  v.literal("review"),
  v.literal("blocked"),
);

export type AiMediaStatus =
  | "clean"
  | "review"
  | "blocked";

const SCAN_HEAD_BYTES = 128 * 1024; // metadata lives at the head of the file

/** Scan raw image bytes for generator metadata markers. */
export function scanImageBytes(bytes: ArrayBuffer): AiScanResult {
  const head = new Uint8Array(bytes, 0, Math.min(bytes.byteLength, SCAN_HEAD_BYTES));
  let text = "";
  for (let i = 0; i < head.length; i++) {
    text += String.fromCharCode(head[i]);
  }
  const lower = text.toLowerCase();
  for (const marker of IMAGE_GENERATOR_MARKERS) {
    if (lower.includes(marker)) {
      return {
        status: "blocked",
        reason: `This image carries AI-generator metadata (${marker.trim()}), which isn't allowed on PureWire.`,
      };
    }
  }
  return { status: "clean" };
}

/**
 * Scan every image in a media list by reading its bytes from storage.
 * Runs as an action because `storage.get` is only available in actions.
 * Mutations call this via `ctx.runAction`.
 */
export const scanMediaForAi = action({
  args: {
    media: v.array(
      v.object({
        storageId: v.id("_storage"),
        kind: v.string(),
      }),
    ),
  },
  returns: v.union(
    v.object({ status: v.literal("clean") }),
    v.object({ status: v.literal("review"), reason: v.string() }),
    v.object({ status: v.literal("blocked"), reason: v.string() }),
  ),
  handler: async (ctx, { media }): Promise<AiScanResult> => {
    for (const item of media) {
      if (item.kind !== "image") {
        continue;
      }
      const blob = await ctx.storage.get(item.storageId);
      if (blob === null) {
        continue;
      }
      const result: AiScanResult = scanImageBytes(await blob.arrayBuffer());
      if (result.status !== "clean") {
        return result;
      }
    }
    return { status: "clean" };
  },
});
