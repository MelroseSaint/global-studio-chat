#!/usr/bin/env node
/**
 * Generate src/convex/emailDomainList.ts from the maintained denylist
 * files in blocked-email-domains/ (the source of truth). Convex bundles
 * TypeScript, not loose text files, so the denylist is compiled into a
 * typed module at build time.
 *
 * Normalization per line: trim, lowercase, strip a trailing dot, strip a
 * leading `*.` / `.` (a wildcard entry is just the bare domain — the gate
 * blocks subdomains of every listed domain anyway). Blank lines and `#`
 * comments are skipped. Entries are deduplicated and sorted.
 *
 * Run after editing blocked-email-domains/*.txt:
 *   node scripts/generate-email-domain-list.mjs
 *
 * A CI guard (static-audit workflow) fails if the generated module drifts
 * from the txt files, so the two can never silently fall out of sync.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

const CATEGORIES = ["disposable", "temporary", "mail-forwarding", "custom"];

const entries = new Map(); // domain -> category (first category wins)
let skipped = 0;

for (const category of CATEGORIES) {
  const file = join(ROOT, "blocked-email-domains", `${category}.txt`);
  const text = readFileSync(file, "utf8");
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line.length === 0 || line.startsWith("#")) continue;
    // Normalize: lowercase, strip trailing dot and leading `*.` / `.`.
    let domain = line.toLowerCase().replace(/\.$/, "");
    if (domain.startsWith("*.")) domain = domain.slice(2);
    if (domain.startsWith(".")) domain = domain.slice(1);
    // A bare TLD or an obviously malformed entry is useless — drop it.
    if (
      domain.length < 4 ||
      !domain.includes(".") ||
      /\s/.test(domain) ||
      /[^a-z0-9.-]/.test(domain)
    ) {
      skipped++;
      continue;
    }
    if (!entries.has(domain)) {
      entries.set(domain, category);
    }
  }
}

const sorted = [...entries.entries()].sort((a, b) =>
  a[0].localeCompare(b[0]),
);

const body = sorted
  .map(
    ([domain, category]) =>
      `  { domain: ${JSON.stringify(domain)}, category: ${JSON.stringify(category)} },`,
  )
  .join("\n");

const out = `/**
 * GENERATED by scripts/generate-email-domain-list.mjs — do not edit by hand.
 * Source of truth: the blocked-email-domains/*.txt files (run the generator
 * after editing them; the static-audit CI guard fails on drift).
 *
 * Every entry blocks the domain AND any of its subdomains, so services that
 * hand out per-user subdomains (anything.mailinator.com) are covered by a
 * single bare-domain line.
 */
export type EmailDomainCategory =
  | "disposable"
  | "temporary"
  | "mail-forwarding"
  | "custom";

export interface EmailDomainEntry {
  domain: string;
  category: EmailDomainCategory;
}

export const DISPOSABLE_EMAIL_DOMAINS: readonly EmailDomainEntry[] = [
${body}
] as const;

export const EMAIL_DOMAIN_COUNT = ${sorted.length};
`;

const outPath = join(ROOT, "src", "convex", "emailDomainList.ts");

if (process.argv.includes("--check")) {
  // Drift guard for CI: regenerate in memory and compare byte-for-byte
  // with the committed module. Exit 1 (and print the fix) on any drift so
  // the generated list can never silently fall out of sync with the
  // maintained txt files.
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // Missing file is drift too.
  }
  if (current === out) {
    console.log(`emailDomainList.ts is in sync — ${sorted.length} domains.`);
    process.exit(0);
  }
  console.error(
    `Drift detected: src/convex/emailDomainList.ts does not match ` +
      `blocked-email-domains/*.txt (${sorted.length} domains). ` +
      `Run: node scripts/generate-email-domain-list.mjs`,
  );
  process.exit(1);
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(
  `Wrote ${outPath} — ${sorted.length} domains (${skipped} malformed lines skipped).`,
);
